def get_lang() -> str:
    lang = load_config().get("language", "tr")
    return lang if lang in STRINGS else "tr"


def set_lang(lang: str) -> None:
    if lang not in STRINGS:
        raise ValueError(lang)
    cfg = load_config()
    cfg["language"] = lang
    save_config(cfg)


def t(key: str, **kwargs) -> str:
    lang = get_lang()
    text = STRINGS.get(lang, STRINGS["tr"]).get(key)
    if text is None:
        text = STRINGS["en"].get(key) or STRINGS["tr"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
